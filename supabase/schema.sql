-- ---------- 7.2 Tự tạo profile khi có user mới (BẮT BUỘC cho multi-user) ----------
-- Trước V7, hàng profiles chỉ sinh ra khi client chủ động upsert goals.
-- User đăng ký rồi bỏ đi giữa chừng sẽ không có profile => join hụt, admin không đếm được.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id, display_name, avatar_hue)
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data->>'display_name',''),
      nullif(new.raw_user_meta_data->>'full_name',''),
      nullif(new.raw_user_meta_data->>'name',''),
      split_part(coalesce(new.email,'hoc-vien'),'@',1)
    ),
    (abs(hashtext(new.id::text)) % 361)
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill cho user đã đăng ký trước khi có trigger.
insert into public.profiles (user_id, display_name, avatar_hue)
select u.id,
       coalesce(nullif(u.raw_user_meta_data->>'display_name',''), split_part(coalesce(u.email,'hoc-vien'),'@',1)),
       (abs(hashtext(u.id::text)) % 361)
from auth.users u
left join public.profiles p on p.user_id = u.id
where p.user_id is null;

