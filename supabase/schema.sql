-- ---------- 7.5 View tổng hợp server-side (RLS vẫn áp dụng nhờ security_invoker) ----------
drop view if exists public.v_user_daily;
create view public.v_user_daily
with (security_invoker = true) as
select
  user_id,
  event_date as study_date,
  count(*) filter (where event_type in ('review','quiz_answer','drill_answer'))::int as reviews,
  count(*) filter (where is_new_item)::int                                            as new_items,
  count(*) filter (where is_correct is true)::int                                     as correct_count,
  count(*) filter (where is_correct is false)::int                                    as wrong_count,
  coalesce(sum(duration_seconds),0)::int                                              as study_seconds,
  count(*) filter (where event_type = 'exam_submit')::int                             as exam_attempts,
  max(occurred_at)                                                                    as last_activity
from public.learning_events
group by user_id, event_date;

drop view if exists public.v_user_overview;
create view public.v_user_overview
with (security_invoker = true) as
select
  p.user_id,
  p.display_name,
  p.daily_minutes_goal,
  p.daily_reviews_goal,
  p.target_exam_date,
  (select count(*) from public.study_progress sp where sp.user_id = p.user_id)                                  as tracked_items,
  (select count(*) from public.study_progress sp where sp.user_id = p.user_id and sp.status = 'mastered')       as mastered_items,
  (select count(*) from public.study_progress sp where sp.user_id = p.user_id and sp.due_at <= now())           as due_items,
  (select count(*) from public.study_sessions ss where ss.user_id = p.user_id and ss.ended_at is not null)      as finished_sessions,
  (select max(le.occurred_at) from public.learning_events le where le.user_id = p.user_id)                      as last_activity
from public.profiles p;

