-- ---------- 8.2 RPC ghi event có kiểm tra hạn mức ----------
create or replace function public.log_learning_events(events jsonb)
returns table(accepted integer, rejected integer, quota_used integer, quota_limit integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  uid        uuid := auth.uid();
  lim        integer := public.quota_limit_events();
  used       integer;
  incoming   integer;
  room       integer;
  inserted   integer := 0;
begin
  if uid is null then
    raise exception 'Chua dang nhap' using errcode = '28000';
  end if;
  if jsonb_typeof(events) <> 'array' then
    raise exception 'events phai la mang JSON' using errcode = '22023';
  end if;

  incoming := jsonb_array_length(events);
  if incoming = 0 then
    return query select 0, 0, 0, lim;
    return;
  end if;
  -- Chặn payload quá lớn trong một lần gọi.
  if incoming > 500 then
    raise exception 'Toi da 500 event moi lan goi' using errcode = '22023';
  end if;

  insert into public.usage_quota (user_id, quota_date, events_written, rpc_calls)
  values (uid, current_date, 0, 1)
  on conflict (user_id, quota_date) do update
    set rpc_calls = public.usage_quota.rpc_calls + 1, updated_at = now();

  select events_written into used
  from public.usage_quota where user_id = uid and quota_date = current_date;

  room := greatest(0, lim - used);
  if room = 0 then
    return query select 0, incoming, used, lim;
    return;
  end if;

  with candidate as (
    select
      coalesce((e->>'event_id')::uuid, gen_random_uuid())          as event_id,
      e->>'event_type'                                              as event_type,
      nullif(left(coalesce(e->>'item_key',''), 200), '')            as item_key,
      nullif(e->>'item_type','')                                    as item_type,
      nullif(left(coalesce(e->>'topic',''), 120), '')               as topic,
      nullif(e->>'quality','')::smallint                            as quality,
      nullif(e->>'is_correct','')::boolean                          as is_correct,
      coalesce(nullif(e->>'is_new_item','')::boolean, false)        as is_new_item,
      -- Chặn số liệu vô lý: một lượt học không thể kéo dài quá 2 giờ.
      least(greatest(coalesce(nullif(e->>'duration_seconds','')::integer, 0), 0), 7200) as duration_seconds,
      nullif(e->>'session_id','')::uuid                             as session_id,
      coalesce(nullif(e->>'occurred_at','')::timestamptz, now())    as occurred_at,
      coalesce(nullif(e->>'event_date','')::date, current_date)     as event_date,
      nullif(left(coalesce(e->>'client_id',''), 64), '')            as client_id,
      coalesce(e->'metadata', '{}'::jsonb)                          as metadata,
      row_number() over ()                                          as rn
    from jsonb_array_elements(events) as e
  ),
  valid as (
    select * from candidate
    where rn <= room
      and event_type in ('review','quiz_answer','drill_answer','exam_submit','session_start','session_end')
      -- Không nhận event của tương lai hay quá 90 ngày trước: chống bịa lịch sử học.
      and occurred_at <= now() + interval '10 minutes'
      and occurred_at >= now() - interval '90 days'
  ),
  ins as (
    insert into public.learning_events
      (event_id, user_id, event_type, item_key, item_type, topic, quality, is_correct,
       is_new_item, duration_seconds, session_id, occurred_at, event_date, client_id, metadata)
    select event_id, uid, event_type, item_key, item_type, topic, quality, is_correct,
           is_new_item, duration_seconds, session_id, occurred_at, event_date, client_id, metadata
    from valid
    on conflict (event_id) do nothing
    returning 1
  )
  select count(*)::integer into inserted from ins;

  update public.usage_quota
     set events_written = events_written + inserted, updated_at = now()
   where user_id = uid and quota_date = current_date;

  return query select inserted, incoming - inserted, used + inserted, lim;
end;
$$;

revoke all on function public.log_learning_events(jsonb) from public, anon;
grant execute on function public.log_learning_events(jsonb) to authenticated;

